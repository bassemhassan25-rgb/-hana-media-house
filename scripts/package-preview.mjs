import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
const output=process.argv[2];if(!output)throw Error('Provide output directory');
await mkdir(output,{recursive:true});
let html=await readFile('dist/index.html','utf8');let css=await readFile('styles.css','utf8');
const font='assets/fonts/space-grotesk-latin-variable.woff2';
css=css.replaceAll(font,`data:font/woff2;base64,${(await readFile(font)).toString('base64')}`);
const config=(await readFile('content.js','utf8')).replace('export const content','const content');
const lib=(await readFile('lib.js','utf8')).replaceAll('export function','function');
const app='const c=content;const e=escapeHTML;\n'+(await readFile('app.js','utf8')).replace(/^import .*;\n/gm,'');
html=html.replace(/<link[^>]*rel="preload"[^>]*as="font"[^>]*>/g,'');
html=html.replace('<link rel="stylesheet" href="styles.css">',`<style>${css}</style>`).replace('<script type="module" src="app.js"></script>','');
html=html.replace('</body>',`<script type="module">${config}\n${lib}\n${app}</script></body>`);
await cp('assets',output+'/assets',{recursive:true});
await writeFile(output+'/HANA-preview.html',html);
console.log('Standalone preview written with bundled font and local media.');
